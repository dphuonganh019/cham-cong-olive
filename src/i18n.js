let LANG = 'vi';
const LANGS = ['en', 'vi'];
function detectLang() {
  const n = (typeof navigator !== 'undefined' && (navigator.language || '')) || '';
  return /^vi\b/i.test(n) ? 'vi' : 'en';
}
function setLang(l) { LANG = LANGS.includes(l) ? l : 'en'; }
function T(key, p) {
  if (p && Number(String(p.n).replace(',', '.')) === 1 && I18N[key + '.one']) key += '.one';
  const row = I18N[key];
  let s = row ? row[LANG === 'vi' ? 1 : 0] : key;
  return p ? s.replace(/\{(\w+)\}/g, (m, k) => (p[k] != null ? p[k] : m)) : s;
}
const LOCALE = () => (LANG === 'vi' ? 'vi-VN' : 'en-US');
const fmtNum = n => Number(n).toLocaleString(LOCALE());
const fmtVnd = n => Math.round(n).toLocaleString(LOCALE()) + ' ₫';
const fmtHdec = min => (Math.round(min / 60 * 100) / 100).toLocaleString(LOCALE());
const fmtDist = m => (m >= 1000 ? (Math.round(m / 100) / 10).toLocaleString(LOCALE()) + ' km' : Math.round(m) + ' m');
const dowShort = i => T('dow.' + i);
const monthName = m => T('month.' + m);
function holidayName(h) { return h && h.key ? T('hol.' + h.key, { n: h.n }) : (h && h.name) || ''; }
function dayLabel(dt) { return dt.holiday ? holidayName(dt.holiday) : T('day.' + dt.type); }
/* Log entries: new ones are {t, code, p}; entries saved by older versions are {t, text}. */
function eventText(e) {
  if (!e.code) return e.text || '';
  const p = { ...(e.p || {}) };
  if (p.src) p.src = T('src.' + p.src);
  return T('ev.' + e.code, p);
}
function signalText(s) {
  if (s.text && !s.type) return s.text;
  const parts = [T('sig.' + s.type)];
  parts.push(s.dist != null ? (s.acc != null ? T('sig.distAcc', { dist: fmtDist(s.dist), acc: fmtDist(s.acc) }) : T('sig.dist', { dist: fmtDist(s.dist) })) : T('sig.noLoc'));
  if (s.rejected) parts.push(T('sig.rejected'));
  if (s.src === 'recheck') parts.push(T('sig.recheck'));
  if (s.src === 'service') parts.push(T('sig.service'));
  if (s.wifi) parts.push(T('sig.wifi'));
  if (s.info) parts.push(T('sig.info'));
  return parts.join(' · ');
}
/* Static markup: data-i18n (text), data-i18n-html (trusted markup), data-i18n-ph (placeholder), data-i18n-aria (aria-label). */
function applyStaticText(root) {
  const r = root || document;
  r.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = T(el.dataset.i18n); });
  r.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = T(el.dataset.i18nHtml); });
  r.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = T(el.dataset.i18nPh); });
  r.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', T(el.dataset.i18nAria)); });
}
